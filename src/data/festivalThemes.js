// Auto Date Calendar Theme Detector Helper
export const detectCurrentAutoFestivalTheme = () => {
  const today = new Date();
  const month = today.getMonth() + 1; // 1 to 12
  const date = today.getDate();

  // 15 August Independence Day (Active Aug 1 - Aug 17)
  if (month === 8 && date >= 1 && date <= 17) {
    return FESTIVAL_THEMES.independenceDay;
  }

  // Raksha Bandhan (Active Aug 18 - Aug 20)
  if (month === 8 && date >= 18 && date <= 20) {
    return FESTIVAL_THEMES.rakshabandhan;
  }

  // Janmashtami (Active Aug 25 - Aug 27)
  if (month === 8 && date >= 25 && date <= 27) {
    return FESTIVAL_THEMES.janmashtami;
  }

  // Diwali (Active Oct 28 - Nov 3)
  if ((month === 10 && date >= 28) || (month === 11 && date <= 3)) {
    return FESTIVAL_THEMES.diwali;
  }

  // Default Theme
  return FESTIVAL_THEMES.default;
};
